#!/usr/bin/env python3
"""Compute the headline accuracy table for the 2026-05-04 MedQA run.

Inputs:  results/*_per_question.jsonl
Output:  reports/01_accuracy_table.md

Run from bench-public/medqa-2026-05-04/.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

ARMS = [
    ("asha",   "Asha (DNAi)"),
    ("opus45", "Claude Opus 4.5"),
    ("o4mini", "OpenAI o4-mini-high"),
    ("gemini", "Gemini 3.1 Pro Preview"),
    ("gpt4o",  "GPT-4o"),
]


def wilson_ci(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    denom = 1.0 + z * z / n
    center = p + z * z / (2 * n)
    margin = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return ((center - margin) / denom, (center + margin) / denom)


def main() -> None:
    here = Path(__file__).resolve().parent.parent
    results_dir = here / "results"
    out = here / "reports" / "01_accuracy_table.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# MedQA 2026-05-04 — Accuracy Table\n",
        "Generated by `scripts/compute_accuracy.py`.\n",
        "| Arm | Correct | n | Accuracy | Wilson 95% CI | Parse failures |",
        "|-----|--------:|--:|---------:|-------------:|---------------:|",
    ]
    print(lines[0])
    for arm_key, arm_label in ARMS:
        fp = results_dir / f"{arm_key}_per_question.jsonl"
        if not fp.exists():
            print(f"WARN: missing {fp}")
            continue
        recs = [json.loads(L) for L in fp.read_text().splitlines() if L.strip()]
        n = len(recs)
        correct = sum(1 for r in recs if r.get("correct"))
        parse_fail = sum(1 for r in recs if not r.get("parsed"))
        lo, hi = wilson_ci(correct, n)
        line = (
            f"| {arm_label} | {correct} | {n} | "
            f"{correct/n*100:.2f}% | [{lo*100:.2f}, {hi*100:.2f}] | {parse_fail} |"
        )
        lines.append(line)
        print(line)
    out.write_text("\n".join(lines) + "\n")
    print(f"\nwrote: {out}")


if __name__ == "__main__":
    main()
